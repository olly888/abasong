import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
const source = JSON.parse(readFileSync("docs/design/tokens-v3.json", "utf8"));
const prototypeRoot = "design/abasong-independent-v1";
const inviteRoot = "deploy/invitation/invite";
const header = "// Generated by scripts/d0/generate-tokens.mjs. Do not edit.";
function resolve(value) {
  if (value && typeof value === "object" && "$value" in value)
    return resolve(value.$value);
  if (typeof value === "string" && /^\{[^}]+\}$/.test(value)) {
    const target = value
      .slice(1, -1)
      .split(".")
      .reduce((node, key) => node[key], source);
    return resolve(target);
  }
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(
    Object.entries(value)
      .filter(([key]) => !key.startsWith("$"))
      .map(([key, child]) => [key, resolve(child)]),
  );
}
function leaves(node, path = []) {
  return Object.entries(node).flatMap(([key, value]) => {
    if (key.startsWith("$")) return [];
    return "$value" in value
      ? [[...path, key, value.$value]]
      : leaves(value, [...path, key]);
  });
}
const css = [
  "/* Generated from docs/design/tokens-v3.json. Do not edit. */",
  ":root {",
];
for (const leaf of leaves(source)) {
  const value = leaf.pop();
  const formatted =
    typeof value === "object"
      ? `${value.value}${value.unit}`
      : typeof value === "string" && value.startsWith("{")
        ? `var(--ab-${value.slice(1, -1).replaceAll(".", "-")})`
        : value;
  css.push(`  --ab-${leaf.join("-")}: ${formatted};`);
}
css.push("}", "");
for (const path of [
  "docs/design/tokens-v3.css",
  `${prototypeRoot}/v12.1/tokens.css`,
  `${prototypeRoot}/v12.1-import/tokens.css`,
  `${inviteRoot}/tokens.css`,
])
  writeFileSync(path, css.join("\n"));

const { version, icons } = JSON.parse(
  readFileSync("docs/design/icons-lucide.json", "utf8"),
);
const paths = Object.fromEntries(
  Object.entries(icons).map(([name, icon]) => [name, icon.paths]),
);
const glyphs = JSON.stringify(paths, null, 2);
const iconHeader = `// Lucide ${version} glyphs. See docs/design/lucide-LICENSE.txt.`;
const wordmark = readFileSync(
  "docs/design/brand/abasong_wordmark_primary.svg",
  "utf8",
);
const nativeWordmark = wordmark.replace(/<title>[^<]*<\/title>/, "");
writeFileSync(
  "packages/ui/src/index.ts",
  `${header}\nexport const tokens = ${JSON.stringify(resolve(source), null, 2)} as const;\n\n${iconHeader}\nexport const iconPaths = ${glyphs} as const;\nexport const brandWordmark = ${JSON.stringify(nativeWordmark.trim())};\n`,
);
writeFileSync(
  `${prototypeRoot}/v12.1-experience/icons.js`,
  `${header}\n${iconHeader}\nconst iconPaths = ${glyphs};\n`,
);
for (const path of [
  `${prototypeRoot}/assets/brand/abasong_wordmark_primary.svg`,
  `${inviteRoot}/assets/brand/abasong_wordmark_primary.svg`,
]) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, wordmark);
}
